// 非流式请求下上游仍被强制成 SSE，透传上游响应头会把 text/event-stream 带给客户端，
// 而 body 是网关重新序列化的 JSON —— 头体不符。
func TestHandleCCBufferedFromAnthropic_WritesJSONContentType(t *testing.T) {
	t.Parallel()
	gin.SetMode(gin.TestMode)

	rec := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(rec)

	resp := &http.Response{
		Header: http.Header{
			"x-request-id":     []string{"rid_cc_ct"},
			"Content-Type":     []string{"text/event-stream; charset=utf-8"},
			"Content-Encoding": []string{"gzip"},
		},
		Body: io.NopCloser(strings.NewReader(strings.Join([]string{
			`event: message_start`,
			`data: {"type":"message_start","message":{"id":"msg_3","type":"message","role":"assistant","content":[],"model":"claude-sonnet-4.5","stop_reason":"","usage":{"input_tokens":5}}}`,
			``,
			`event: content_block_start`,
			`data: {"type":"content_block_start","index":0,"content_block":{"type":"text","text":"hi"}}`,
			``,
			`event: message_delta`,
			`data: {"type":"message_delta","delta":{"stop_reason":"end_turn"},"usage":{"output_tokens":2}}`,
			``,
		}, "\n"))),
	}

	svc := &GatewayService{responseHeaderFilter: responseheaders.CompileHeaderFilter(config.ResponseHeaderConfig{})}
	result, err := svc.handleCCBufferedFromAnthropic(resp, c, "gpt-5", "claude-sonnet-4.5", nil, time.Now())
	require.NoError(t, err)
	require.NotNil(t, result)

	require.Equal(t, "application/json; charset=utf-8", rec.Header().Get("Content-Type"))
	require.Empty(t, rec.Header().Get("Content-Encoding"))
	require.Equal(t, "rid_cc_ct", rec.Header().Get("x-request-id"))
	require.Contains(t, rec.Body.String(), `"object":"chat.completion"`)
}
