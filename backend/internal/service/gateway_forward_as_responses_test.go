// /v1/responses 非流式聚合与 chat/completions 同源：占位 input({}) 不能拼在
// input_json_delta 前面，否则 function_call.arguments 不是合法 JSON。
func TestHandleResponsesBufferedStreamingResponse_FunctionCallArgumentsAreValidJSON(t *testing.T) {
	t.Parallel()
	gin.SetMode(gin.TestMode)

	rec := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(rec)

	resp := &http.Response{
		Body: io.NopCloser(strings.NewReader(strings.Join([]string{
			`event: message_start`,
			`data: {"type":"message_start","message":{"id":"msg_tool","type":"message","role":"assistant","content":[],"model":"glm-5.2","usage":{"input_tokens":10}}}`,
			``,
			`event: content_block_start`,
			`data: {"type":"content_block_start","index":0,"content_block":{"type":"tool_use","id":"toolu_1","name":"read_file","input":{}}}`,
			``,
			`event: content_block_delta`,
			`data: {"type":"content_block_delta","index":0,"delta":{"type":"input_json_delta","partial_json":"{\"file_path\": \"/a/b.md\"}"}}`,
			``,
			`event: message_delta`,
			`data: {"type":"message_delta","delta":{"stop_reason":"tool_use"},"usage":{"output_tokens":6}}`,
			``,
		}, "\n"))),
	}

	svc := &GatewayService{}
	_, err := svc.handleResponsesBufferedStreamingResponse(resp, c, "glm-5.2", "glm-5.2", nil, time.Now())
	require.NoError(t, err)

	args := gjson.Get(rec.Body.String(), `output.#(type=="function_call").arguments`)
	require.True(t, args.Exists(), "function_call arguments missing: %s", rec.Body.String())
	require.Equal(t, `{"file_path": "/a/b.md"}`, args.String())
	require.True(t, json.Valid([]byte(args.String())), "arguments must be valid JSON, got %q", args.String())
}
